"""Stage P1.3: 20-history annular synthetic control bank.

The bank is generated by the archived S8 chronological simulator with only the
attenuation stress kernel changed to ann2. The ETAS backbone, mark law, smooth
background and 30-395/395-760 windows are the archived S8 moderate design. Each
history is fitted with a null (eta=0), a mono-kernel estimator and an ann2-kernel
estimator; the true ann2 law supplies the oracle ceiling.
"""
from __future__ import annotations

import argparse
import json
import math
import sys
import time
from concurrent.futures import ProcessPoolExecutor, as_completed
from pathlib import Path

import numpy as np
from threadpoolctl import threadpool_limits

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from experiments.pathway1_annular_attenuation import annular as A  # noqa: E402
from experiments.pathway1_annular_attenuation import synthetic as SY  # noqa: E402
from experiments.pathway1_annular_attenuation.native import Native, DEFAULT_OUTPUT  # noqa: E402

TRUE_BACKBONE = dict(a=math.log(0.25), d=0.2, n=0.35, c=0.05, p=1.3,
                     ell=15.0, psi=5.0, beta=2.0, sigma=10.0, gamma=SY.GAMMA)
POSITIVE_TRIPLETS = ((0.1, 5.0, 1.0), (0.3, 15.0, 5.0), (0.7, 30.0, 30.0), (1.5, 50.0, 7.0))


def native_v2(threads=1):
    return Native(DEFAULT_OUTPUT / "annular.dll", threads=threads, kernel="ann2", scaled=False)


def generate_bank(output, seeds, eta, ell, psi):
    bank = output / "bank"
    bank.mkdir(parents=True, exist_ok=True)
    receipts = []
    for seed in seeds:
        path = bank / f"{seed}.npz"
        receipt_path = bank / f"{seed}.json"
        if path.exists() and receipt_path.exists():
            existing = json.loads(receipt_path.read_text(encoding="utf-8"))
            if (abs(existing["law"]["eta"] - eta) > 1e-12
                    or abs(existing["law"]["ell"] - ell) > 1e-12
                    or abs(existing["law"]["psi"] - psi) > 1e-12):
                raise ValueError("existing synthetic bank was generated with a different law")
            receipts.append(existing)
            continue
        started = time.time()
        rows, metadata, counters, law = SY.generate_history(seed, eta, ell, psi)
        np.savez_compressed(path, rows=rows)
        receipt = dict(
            seed=int(seed),
            law=dict(a=law.a, d=law.d, n=law.n, c=law.c, p=law.p, eta=law.eta,
                     ell=law.ell, psi=law.psi, sigma=law.sigma, beta=law.beta,
                     horizon=law.horizon, T0=law.T0, background=law.background),
            metadata=metadata,
            counters=counters,
            thinning_fraction=SY.thinning_fraction(counters),
            n_train=int(np.sum((rows[:, 0] >= 30) & (rows[:, 0] < 395))),
            n_test=int(np.sum(rows[:, 0] >= 395)),
            n_total=int(len(rows)),
            elapsed_seconds=float(time.time() - started),
        )
        receipt_path.write_text(json.dumps(receipt, indent=2, allow_nan=False) + "\n", encoding="utf-8")
        receipts.append(receipt)
        print("generate", seed, receipt["thinning_fraction"], receipt["n_test"], flush=True)
    protocol = dict(
        schema="pathway1_annular_synthetic_bank_protocol_v1",
        generator_source=str(SY.GENERATOR.relative_to(ROOT).as_posix()),
        generator_source_sha256=A.sha256(SY.GENERATOR),
        seeds=[int(s) for s in seeds],
        law=dict(a=TRUE_BACKBONE["a"], d=TRUE_BACKBONE["d"], n=TRUE_BACKBONE["n"],
                 c=TRUE_BACKBONE["c"], p=TRUE_BACKBONE["p"], eta=float(eta),
                 ell_km=float(ell), psi_days=float(psi), sigma_km=TRUE_BACKBONE["sigma"],
                 beta=TRUE_BACKBONE["beta"], gamma=TRUE_BACKBONE["gamma"]),
        windows=dict(train=[30.0, 395.0], test=[395.0, 760.0]),
        kernel="ann2 (16 v^2/(1+v)^4), unscaled ell_j = ell0",
        attenuation="total intensity exp(-eta G), applied to immigrant and offspring candidates",
        target_match="S8 moderate thinning 25-30% and about 95 test events",
        achieved=dict(
            mean_thinning=float(np.mean([r["thinning_fraction"] for r in receipts])),
            mean_test_events=float(np.mean([r["n_test"] for r in receipts])),
            thinning_range=[float(min(r["thinning_fraction"] for r in receipts)),
                            float(max(r["thinning_fraction"] for r in receipts))],
            test_event_range=[int(min(r["n_test"] for r in receipts)),
                              int(max(r["n_test"] for r in receipts))],
        ),
        notes="Only the attenuation stress kernel is replaced. The archived S8 generator source is imported read-only; the ann2 stress is injected at run time.",
    )
    (output / "bank_protocol.json").write_text(json.dumps(protocol, indent=2, allow_nan=False) + "\n", encoding="utf-8")
    return protocol


def _evaluate_test(synthetic, theta, model):
    value, gradient = synthetic.evaluate(theta, "null" if model == "null" else model, order=16)
    return dict(joint=float(value["joint"]), nll=float(value["nll"]), P=float(value["P"]),
                E=float(value["E"]), M=float(value["M"]), gradient=[float(v) for v in gradient])


def fit_history(seed, bank, output, order=8):
    receipt = json.loads((bank / f"{seed}.json").read_text(encoding="utf-8"))
    rows = np.load(bank / f"{seed}.npz")["rows"]
    started = time.time()
    native = native_v2(threads=1)
    modules = SY.load_s8().archived()
    phase_train = SY.make_phase(rows, receipt["metadata"], 30.0, 395.0, native, modules)
    phase_test = SY.make_phase(rows, receipt["metadata"], 395.0, 760.0, native, modules)
    mono = SY.FastSyntheticAnnular(phase_train, native, kernel="mono",
                                   spatial_order=12, time_order=8)
    ann2 = SY.FastSyntheticAnnular(phase_train, native, kernel="ann2",
                                   spatial_order=12, time_order=8)
    test_mono = SY.FastSyntheticAnnular(phase_test, native, kernel="mono",
                                        spatial_order=20, time_order=16)
    test_ann2 = SY.FastSyntheticAnnular(phase_test, native, kernel="ann2",
                                        spatial_order=20, time_order=16)
    n_train = int(np.sum((rows[:, 0] >= 30) & (rows[:, 0] < 395)))
    null_starts = SY.null_starts(n_train)[:3]
    null_fit = SY.fit_arm(mono, "null", null_starts, order=order)
    null_theta = np.asarray(null_fit["selected"]["parameters"], dtype=float)
    null_nll = float(null_fit["selected"]["nll"])
    fits = {}
    for name, synthetic in (("mono", mono), ("ann2", ann2)):
        starts = [null_theta.copy()]
        for eta, ell, psi in POSITIVE_TRIPLETS[:3]:
            x = null_theta.copy()
            x[5] = eta
            x[6] = math.log(ell)
            x[7] = math.log(psi)
            starts.append(x)
        fit = SY.fit_arm(synthetic, name, starts, order=order)
        selected = dict(fit["selected"])
        nested = bool(null_nll <= selected["nll"] + 1e-9)
        if nested:
            selected = dict(start=-1, success=True, message="exact eta=0 candidate retained",
                            nfev=1, nit=0, nll=null_nll,
                            parameters=[float(v) for v in null_theta],
                            gradient=[0.0] * 8, seconds=0.0, nested_null=True)
        fits[name] = dict(selected=selected, records=fit["records"], nested_null=nested)
    true_theta = np.array([TRUE_BACKBONE["a"], TRUE_BACKBONE["d"], TRUE_BACKBONE["n"],
                           math.log(TRUE_BACKBONE["c"]), TRUE_BACKBONE["p"],
                           float(receipt["law"]["eta"]), math.log(TRUE_BACKBONE["ell"]),
                           math.log(TRUE_BACKBONE["psi"])])
    test = dict(
        null=_evaluate_test(test_mono, null_theta, "null"),
        mono=_evaluate_test(test_mono, np.asarray(fits["mono"]["selected"]["parameters"]), "mono"),
        ann2=_evaluate_test(test_ann2, np.asarray(fits["ann2"]["selected"]["parameters"]), "ann2"),
        oracle=_evaluate_test(test_ann2, true_theta, "ann2"),
    )
    null_joint = test["null"]["joint"]
    mono_gain = float(test["mono"]["joint"] - null_joint)
    ann2_gain = float(test["ann2"]["joint"] - null_joint)
    oracle_gain = float(test["oracle"]["joint"] - null_joint)
    row = dict(
        seed=int(seed),
        n_train=int(n_train),
        n_test=int(receipt["n_test"]),
        thinning_fraction=float(receipt["thinning_fraction"]),
        true_law=dict(receipt["law"]),
        true_theta=[float(v) for v in true_theta],
        null=dict(selected=null_fit["selected"], records=null_fit["records"]),
        mono=fits["mono"],
        ann2=fits["ann2"],
        test=test,
        null_test_joint=float(null_joint),
        mono_test_joint=float(test["mono"]["joint"]),
        ann2_test_joint=float(test["ann2"]["joint"]),
        oracle_test_joint=float(test["oracle"]["joint"]),
        mono_gain=mono_gain,
        ann2_gain=ann2_gain,
        oracle_gain=oracle_gain,
        mono_shortfall=float(oracle_gain - mono_gain),
        ann2_shortfall=float(oracle_gain - ann2_gain),
        ann2_recovery_fraction=float(ann2_gain / oracle_gain) if abs(oracle_gain) > 1e-12 else None,
        mono_recovery_fraction=float(mono_gain / oracle_gain) if abs(oracle_gain) > 1e-12 else None,
        selected_eta=dict(mono=float(np.asarray(fits["mono"]["selected"]["parameters"])[5]),
                          ann2=float(np.asarray(fits["ann2"]["selected"]["parameters"])[5])),
        elapsed_seconds=float(time.time() - started),
    )
    A.write_json(output / "histories" / f"{seed}.json", row)
    print("fit", seed, "mono", round(mono_gain, 3), "ann2", round(ann2_gain, 3),
          "oracle", round(oracle_gain, 3), f"{time.time()-started:.1f}s", flush=True)
    return row


def _stats(values):
    values = np.asarray([v for v in values if v is not None], dtype=float)
    if not len(values):
        return dict(N=0)
    return dict(N=int(len(values)), mean=float(values.mean()), median=float(np.median(values)),
                sample_sd=float(values.std(ddof=1)) if len(values) > 1 else 0.0,
                mcse=float(values.std(ddof=1) / math.sqrt(len(values))) if len(values) > 1 else 0.0,
                wins=int(np.sum(values > 0)), values=[float(v) for v in values])


def summarize(output, rows):
    summary = dict(
        schema="pathway1_annular_synthetic_bank_v1",
        passed=True,
        source=str(Path(__file__).relative_to(ROOT).as_posix()),
        source_sha256=A.sha256(Path(__file__)),
        bank_protocol=json.loads((output / "bank_protocol.json").read_text(encoding="utf-8")),
        N=int(len(rows)),
        achieved_thinning=_stats([r["thinning_fraction"] for r in rows]),
        achieved_test_events=_stats([r["n_test"] for r in rows]),
        null_joint=_stats([r["null_test_joint"] for r in rows]),
        mono_gain=_stats([r["mono_gain"] for r in rows]),
        ann2_gain=_stats([r["ann2_gain"] for r in rows]),
        oracle_gain=_stats([r["oracle_gain"] for r in rows]),
        mono_shortfall=_stats([r["mono_shortfall"] for r in rows]),
        ann2_shortfall=_stats([r["ann2_shortfall"] for r in rows]),
        ann2_recovery_fraction=_stats([r["ann2_recovery_fraction"] for r in rows]),
        mono_recovery_fraction=_stats([r["mono_recovery_fraction"] for r in rows]),
        positive_oracle_gain=int(sum(r["oracle_gain"] > 0 for r in rows)),
        ann2_beats_mono=int(sum(r["ann2_gain"] > r["mono_gain"] for r in rows)),
        ann2_beats_null=int(sum(r["ann2_gain"] > 0 for r in rows)),
        mono_beats_null=int(sum(r["mono_gain"] > 0 for r in rows)),
        rows=rows,
    )
    A.write_json(output / "summary.json", summary)
    return summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path,
                        default=ROOT / "validation/live_results/pathway1_annular_20261116/synthetic")
    parser.add_argument("--stage", choices=("generate", "fit", "summary", "all"), default="all")
    parser.add_argument("--seeds", nargs="+", type=int, default=list(range(411001, 411021)))
    parser.add_argument("--eta", type=float, default=0.15)
    parser.add_argument("--ell", type=float, default=15.0)
    parser.add_argument("--psi", type=float, default=5.0)
    parser.add_argument("--workers", type=int, default=4)
    parser.add_argument("--order", type=int, default=8)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    if args.stage in ("generate", "all"):
        protocol = generate_bank(args.output, args.seeds, args.eta, args.ell, args.psi)
        print(json.dumps(protocol["achieved"], indent=2))
    if args.stage in ("fit", "all"):
        rows = []
        with threadpool_limits(limits=1):
            with ProcessPoolExecutor(max_workers=args.workers) as pool:
                futures = {pool.submit(fit_history, seed, args.output / "bank", args.output, args.order): seed
                           for seed in args.seeds}
                for future in as_completed(futures):
                    rows.append(future.result())
        rows.sort(key=lambda r: r["seed"])
        summary = summarize(args.output, rows)
        print(json.dumps({k: summary[k] for k in (
            "mono_gain", "ann2_gain", "oracle_gain", "ann2_recovery_fraction")}, indent=2))
    if args.stage == "summary":
        rows = [json.loads((args.output / "histories" / f"{seed}.json").read_text(encoding="utf-8"))
                for seed in args.seeds]
        summary = summarize(args.output, rows)
        print(json.dumps({k: summary[k] for k in (
            "mono_gain", "ann2_gain", "oracle_gain", "ann2_recovery_fraction")}, indent=2))


if __name__ == "__main__":
    main()
